"""Compressed PNG metadata receives bounded inspection and selective cleaning."""

import struct
import sys
import zlib
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "skills/ai-watermark-scrambler/scripts"))
import image_meta as image


def png(ctype, payload):
    return (
        image.PNG_SIG
        + image._png_chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
        + image._png_chunk(ctype, payload)
        + image._png_chunk(b"IDAT", zlib.compress(b"\x00\xff\x00\x00"))
        + image._png_chunk(b"IEND", b"")
    )


def text_payload(ctype, text):
    header = b"Description\x00\x00" if ctype == b"zTXt" else b"Description\x00\x01\x00en\x00\x00"
    return header + zlib.compress(text)


@pytest.mark.parametrize("ctype", [b"zTXt", b"iTXt"])
def test_compressed_provenance_is_detected_and_removed(ctype):
    data = png(ctype, text_payload(ctype, b"AI generated by Claude; c2pa"))
    assert image.inspect_png(data)[:2] == (True, True)
    cleaned, _ = image.strip_png(data, strip_all_text=False)
    assert ctype not in cleaned
    assert b"IDAT" in cleaned
    assert image.inspect_png(cleaned)[:2] == (False, False)


@pytest.mark.parametrize("ctype", [b"zTXt", b"iTXt"])
def test_benign_compressed_text_is_preserved(ctype):
    data = png(ctype, text_payload(ctype, b"Photo of a garden"))
    assert image.inspect_png(data)[:2] == (False, False)
    assert image.strip_png(data, strip_all_text=False)[0] == data


def test_uncompressed_international_text_is_preserved():
    data = png(b"iTXt", b"Description\x00\x00\x00en\x00\x00Photo of a garden")
    assert image.inspect_png(data)[:2] == (False, False)
    assert image.strip_png(data, strip_all_text=False)[0] == data


def test_selective_clean_reports_no_residual_compressed_provenance(tmp_path, monkeypatch):
    monkeypatch.setattr(image, "which", lambda _name: None)
    monkeypatch.setattr(image, "run_optional_tools", lambda _path: {})
    source, dest = tmp_path / "input.png", tmp_path / "output.png"
    source.write_bytes(png(b"zTXt", text_payload(b"zTXt", b"AI generated by Claude; c2pa")))
    assert image.inspect_image(source).has_c2pa
    result = image.clean_image(source, dest, strip_all_metadata=False)
    assert not result["still_has_c2pa"]
    assert not result["still_has_ai_metadata"]
    assert b"zTXt" not in dest.read_bytes()


@pytest.mark.parametrize("ctype", [b"zTXt", b"iTXt"])
@pytest.mark.parametrize("failure", ["oversized", "invalid", "truncated"])
def test_unreadable_text_is_flagged_and_dropped(ctype, failure, monkeypatch):
    monkeypatch.setattr(image, "MAX_PNG_TEXT_BYTES", 64)
    payload = text_payload(ctype, b"A" * 4096)
    if failure == "invalid":
        payload = text_payload(ctype, b"ordinary text")[:-8] + b"invalid!"
    elif failure == "truncated":
        payload = text_payload(ctype, b"ordinary text")[:-3]
    data = png(ctype, payload)
    assert image.inspect_png(data)[1]
    cleaned, actions = image.strip_png(data, strip_all_text=False)
    assert ctype not in cleaned
    assert any("unreadable" in action for action in actions)
